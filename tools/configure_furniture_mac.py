#!/usr/bin/env python3
"""Keep the rejected/experimental real-renderer MAC path out of normal builds."""
import argparse
from pathlib import Path
p=argparse.ArgumentParser();p.add_argument('--enabled',choices=['0','1'],default='0');a=p.parse_args()
target=Path(__file__).resolve().parents[1]/'sh_src/furniture_mac_config.h'
data=f'/* Generated by Make; explicit experiment only. */\n#define FURNITURE_MAC_EXPERIMENT {a.enabled}\n'
if not target.exists() or target.read_text()!=data:target.write_text(data)
